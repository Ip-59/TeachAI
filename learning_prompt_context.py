"""
Общий контекст обучения для промптов LLM.

Правила: полный текст урока в запросах; задания и ответы — с учётом
реальных возможностей TeachAI (Python ``exec`` в Jupyter, без терминала).

Педагогические решения (тема / относится ли / терминал vs редактор /
копипаста примеров) — через LLM-судью, не через словари маркеров здесь.
"""

from __future__ import annotations

# Мягкий потолок на случай огромного HTML; None = без обрезки в prepare.
FULL_LESSON_MAX_CHARS: int | None = 25000


def practice_runtime_rules_ru() -> str:
    """Ограничения среды практики для любого учебного LLM-запроса."""
    return (
        "=== СРЕДА TEACHAI (обязательно учитывать) ===\n"
        "- Ученик работает в Jupyter: уроки, примеры, тесты, контрольные задания.\n"
        "- Код запускается ТОЛЬКО как Python через встроенный exec (кнопка "
        "«Выполнить код» / ячейка). Отдельного терминала ОС, bash, cmd НЕТ.\n"
        "- Нельзя требовать: «откройте терминал», shell-команды "
        "(python --version, pip install, cd, ls), установку пакетов вручную, "
        "запуск .py из командной строки.\n"
        "- Проверку версии Python оформляй как код: import sys; print(sys.version).\n"
        "- Задания и примеры должны выполняться в одном Python-процессе без "
        "внешнего ввода с клавиатуры (input только если данные уже заданы).\n"
        "- Ответы и шаги — содержательные по материалу урока, не формальные "
        "общие фразы «изучите тему» / «откройте документацию».\n"
    )


def control_task_runtime_rules_ru(lesson_title: str = "") -> str:
    """Жёсткие правила именно для генерации КЗ."""
    title = (lesson_title or "").strip()
    title_hint = f" «{title}»" if title else ""
    return (
        practice_runtime_rules_ru()
        + "\n=== КОНТРОЛЬНОЕ ЗАДАНИЕ ===\n"
        "- Задание ОБЯЗАНО быть строго по текущему уроку"
        f"{title_hint}: по его названию и полному тексту.\n"
        "- Не подменяй тему заданием из другого урока.\n"
        "- Задание ОБЯЗАНО решаться кодом в редакторе TeachAI "
        "(task_code + код ученика после «# Ваш код здесь»).\n"
        "- student_steps / description НЕ должны упоминать терминал или "
        "командную строку.\n"
        "- Если практику с кодом по материалу ЭТОГО урока сформулировать нельзя — "
        "верни is_needed: false (не подменяй заданием из другого урока).\n"
    )


def full_lesson_context_header_ru() -> str:
    return (
        "Ниже — ПОЛНЫЙ текст текущего урока. Опирайся только на него "
        "(и на явные правила среды TeachAI). Не подменяй тему общими "
        "сведениями «про Python вообще», если их нет в уроке.\n"
    )


def lesson_context_block(lesson_text: str) -> str:
    """Блок «полный урок» для user-промпта."""
    text = (lesson_text or "").strip()
    return (
        f"{full_lesson_context_header_ru()}\n"
        f"=== ПОЛНЫЙ ТЕКСТ УРОКА ===\n{text}\n=== КОНЕЦ ТЕКСТА УРОКА ===\n"
    )
