"""Сборка промптов для бенчмарка (урок) без запуска всего TeachAI."""

from __future__ import annotations

from typing import Any

COMMUNICATION_STYLES: dict[str, str] = {
    "formal": (
        "Формальный, академический стиль общения с использованием научной терминологии."
    ),
    "friendly": (
        "Дружелюбный стиль общения, использующий простые объяснения и аналогии."
    ),
    "casual": "Непринужденный, разговорный стиль с элементами юмора.",
    "brief": "Краткий и четкий стиль, фокусирующийся только на ключевой информации.",
}


def build_lesson_system_prompt() -> str:
    """Системный промпт как в LessonGenerator TeachAI."""
    return (
        "Ты - опытный преподаватель Python и эксперт в программировании. "
        "Создавай подробные, информативные и практически полезные уроки БЕЗ финальных "
        "прощаний и пожеланий удачи. КРИТИЧЕСКИ ВАЖНО: ЭТО КУРС ПО PYTHON! ВСЕ ПРИМЕРЫ "
        "КОДА ДОЛЖНЫ БЫТЬ НА PYTHON И ПРАВИЛЬНО ОТФОРМАТИРОВАНЫ С ПЕРЕНОСАМИ СТРОК И "
        "ПРАВИЛЬНЫМИ ОТСТУПАМИ! НЕ ПИШИ КОД В ОДНУ СТРОКУ! КАЖДАЯ СТРОКА КОДА НА "
        "ОТДЕЛЬНОЙ СТРОКЕ!"
    )


def build_lesson_user_prompt(
    course: str,
    section: str,
    topic: str,
    lesson_title: str,
    user_name: str,
    communication_style: str = "friendly",
) -> str:
    """
    Пользовательский промпт урока (упрощённая копия логики LessonGenerator).

    Args:
        course: Название курса.
        section: Раздел.
        topic: Тема.
        lesson_title: Название урока.
        user_name: Имя ученика в промпте.
        communication_style: Ключ стиля общения.

    Returns:
        Текст user-промпта.
    """
    style_description = COMMUNICATION_STYLES.get(
        communication_style, COMMUNICATION_STYLES["friendly"]
    )

    if any(
        word in topic.lower() or word in lesson_title.lower()
        for word in ["список", "list", "словарь", "dict"]
    ):
        topic_specific = (
            "\n- В уроке обязательно должны быть примеры кода с использованием списков "
            "(list), методов append, insert, remove, и словарей (dict), операций "
            "добавления и удаления ключей. Не допускается отсутствие кода по теме!"
        )
    else:
        topic_specific = (
            "\n- В уроке обязательно должны быть примеры кода по теме урока. Если тема "
            "не предполагает кода, явно напиши в начале урока: 'В этом уроке нет кода "
            "для практики.' и не добавляй искусственных примеров."
        )

    return f"""
🚨 КРИТИЧЕСКАЯ ИНСТРУКЦИЯ ДЛЯ API! 🚨
🚨 ЭТО КУРС ПО PYTHON! ВСЕ ПРИМЕРЫ КОДА ДОЛЖНЫ БЫТЬ НА PYTHON! 🚨
🚨 ВСЕ ПРИМЕРЫ КОДА ОБЯЗАТЕЛЬНО ДОЛЖНЫ БЫТЬ ПРАВИЛЬНО ОТФОРМАТИРОВАНЫ! 🚨
🚨 КАЖДАЯ СТРОКА КОДА НА ОТДЕЛЬНОЙ СТРОКЕ! 🚨
🚨 НЕ ПИШИ КОД В ОДНУ СТРОКУ! 🚨
🚨 ЭТО ОБЯЗАТЕЛЬНОЕ ТРЕБОВАНИЕ! 🚨
🚨 ВАЖНО: НЕ ИСПОЛЬЗУЙ print() КОМАНДЫ В ТЕКСТЕ УРОКА! 🚨
🚨 ТЕКСТ УРОКА ДОЛЖЕН БЫТЬ ОБЫЧНЫМ ТЕКСТОМ, А КОД - В БЛОКАХ КОДА! 🚨

Создай образовательный урок по теме:

Курс: {course}
Раздел: {section}
Тема: {topic}
Урок: {lesson_title}

Пользователь: {user_name}

Используй следующий стиль общения: {style_description}

{topic_specific}

Урок должен быть ПОДРОБНЫМ и НАСЫЩЕННЫМ, содержать:
1. Краткое введение в тему с объяснением важности
2. Основные концепции и определения с четкими объяснениями
3. Подробные объяснения с МНОЖЕСТВОМ практических примеров
4. Пошаговые инструкции или алгоритмы (если применимо)
5. Практические применения в реальной жизни
6. Частые ошибки и как их избежать
7. Заключение с КРАТКОЙ сводкой ключевых моментов

ВАЖНЫЕ ТРЕБОВАНИЯ:
- Урок должен быть достаточно подробным, чтобы студент мог изучить тему глубоко
- Включи конкретные примеры кода, формулы или методы (в зависимости от темы)
- Объясни не только "что", но и "как" и "почему"
- Добавь практические советы и рекомендации
- Материал должен быть самодостаточным для понимания темы
- НЕ ЗАВЕРШАЙ урок прощанием, пожеланиями удачи или фразами типа "до новых встреч"
- Заключение должно быть КРАТКИМ резюме ключевых точек, без личных пожеланий

ИСПОЛЬЗУЙ ТОЛЬКО MARKDOWN ДЛЯ ФОРМАТИРОВАНИЯ! НЕ ИСПОЛЬЗУЙ HTML!

ВАЖНО:
- Текст урока должен быть написан обычным текстом
- Примеры кода должны быть в markdown-блоках: ```python ... ```
- Используй markdown для заголовков: # Заголовок, ## Подзаголовок
- Используй markdown для списков: * элемент списка
"""


def build_judge_prompt(
    lesson_meta: dict[str, Any],
    rubric: dict[str, Any],
    labeled_lessons: dict[str, str],
) -> str:
    """
    Промпт для судьи: слепая оценка нескольких текстов урока.

    Args:
        lesson_meta: Метаданные темы (course, topic, lesson).
        rubric: Содержимое rubric.json.
        labeled_lessons: Словарь вида {{"A": text, "B": text, ...}}.

    Returns:
        Текст промпта судьи.
    """
    criteria_lines = []
    for item in rubric["criteria"]:
        criteria_lines.append(
            f"- {item['id']} ({item['name']}): {item['description']} "
            f"— оценка {rubric['scale']['min']}..{rubric['scale']['max']}"
        )
    criteria_block = "\n".join(criteria_lines)

    lessons_block_parts = []
    for label, text in labeled_lessons.items():
        lessons_block_parts.append(
            f"### Урок {label}\n\n{text.strip()}\n\n---\n"
        )
    lessons_block = "\n".join(lessons_block_parts)

    scale = rubric["scale"]["meaning"]
    return f"""
Ты — независимый методист-эксперт по курсам программирования на Python.
Оцени тексты уроков СТРОГО по рубрике. Не угадывай авторов. Не сравнивай
«вкусовщиной»: только критерии ниже.

Контекст задания:
- Курс: {lesson_meta.get("course")}
- Раздел: {lesson_meta.get("section")}
- Тема: {lesson_meta.get("topic")}
- Урок: {lesson_meta.get("lesson")}

Шкала: 0 = {scale["0"]}; 1 = {scale["1"]}; 2 = {scale["2"]}.

Критерии:
{criteria_block}

Тексты (слепые метки):
{lessons_block}

Верни ТОЛЬКО валидный JSON без markdown-обёртки:
{{
  "scores": {{
    "A": {{
      "topic_fit": 0,
      "completeness": 0,
      "density": 0,
      "pedagogy": 0,
      "task_fit": 0,
      "total": 0,
      "comment": "кратко, 1-2 предложения"
    }}
  }}
}}

Поле total = сумма пяти критериев (0..10). Оцени каждый из переданных уроков.
"""
