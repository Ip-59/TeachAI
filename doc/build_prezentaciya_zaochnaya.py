def png_size(path: Path) -> tuple[int, int]:
    with path.open("rb") as fh:
        header = fh.read(24)
    if header[:8] != b"\x89PNG\r\n\x1a\n":
        return 1200, 700
    width, height = struct.unpack(">II", header[16:24])
    return width, height


def set_run(run, text, size, bold=False, color=TEXT, font="Calibri"):
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = font


def add_footer(slide, number: int, total: int) -> None:
    box = slide.shapes.add_textbox(Inches(0.45), Inches(7.15), Inches(12.4), Inches(0.28))
    frame = box.text_frame
    frame.word_wrap = False
    p = frame.paragraphs[0]
    run = p.add_run()
    set_run(
        run,
        f"TeachAI  ·  заочная версия  ·  Университет искусственного интеллекта, Пермь    {number} / {total}",
        11,
        color=MUTED,
    )


def add_title(slide, title: str) -> None:
    bar = slide.shapes.add_shape(1, Inches(0), Inches(0), W, Inches(0.12))
    bar.fill.solid()
    bar.fill.fore_color.rgb = NAVY
    bar.line.fill.background()
    box = slide.shapes.add_textbox(Inches(0.45), Inches(0.28), Inches(12.4), Inches(0.7))
    frame = box.text_frame
    frame.word_wrap = True
    p = frame.paragraphs[0]
    run = p.add_run()
    set_run(run, title, 28, bold=True, color=NAVY)


def add_bullets(slide, bullets: list[str], top=1.15, size=18) -> None:
    box = slide.shapes.add_textbox(Inches(0.55), Inches(top), Inches(12.2), Inches(5.8))
    frame = box.text_frame
    frame.word_wrap = True
    for index, item in enumerate(bullets):
        p = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        p.level = 0
        p.space_after = Pt(8)
        run = p.add_run()
        set_run(run, item, size, color=TEXT)


def add_caption(slide, text: str, top: float) -> None:
    box = slide.shapes.add_textbox(Inches(0.45), Inches(top), Inches(12.4), Inches(0.7))
    frame = box.text_frame
    frame.word_wrap = True
    p = frame.paragraphs[0]
    run = p.add_run()
    set_run(run, text, 14, color=MUTED)


def fit_picture(slide, path: Path, left, top, max_w, max_h):
    width_px, height_px = png_size(path)
    scale = min(max_w / width_px, max_h / height_px)
    pic_w = int(width_px * scale)
    pic_h = int(height_px * scale)
    left_adj = left + (max_w - pic_w) // 2
    return slide.shapes.add_picture(str(path), Emu(left_adj), Emu(top), Emu(pic_w), Emu(pic_h))


