def render_title(slide) -> None:
    band = slide.shapes.add_shape(1, Inches(0), Inches(0), W, Inches(7.5))
    band.fill.solid()
    band.fill.fore_color.rgb = NAVY
    band.line.fill.background()
    box = slide.shapes.add_textbox(Inches(0.7), Inches(1.3), Inches(12), Inches(4.8))
    frame = box.text_frame
    frame.word_wrap = True
    lines = [
        (40, True, "TeachAI"),
        (24, False, "Интеллектуальная система персонализированного обучения на основе LLM"),
        (18, False, ""),
        (20, False, "Дипломный проект  ·  курс «AI/ML - разработчик»"),
        (20, False, "Игорь Пучкин"),
        (20, False, "Университет искусственного интеллекта, Пермь"),
        (18, False, "2026"),
        (16, False, "Заочная версия: читается без устного доклада"),
        (14, False, "Старт обучения и дата защиты — подставить"),
    ]
    for index, (size, bold, text) in enumerate(lines):
        p = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        p.space_after = Pt(6)
        run = p.add_run()
        set_run(run, text, size, bold=bold, color=WHITE)


def render_code(slide, text: str) -> None:
    box = slide.shapes.add_textbox(Inches(0.7), Inches(1.3), Inches(12), Inches(5.5))
    frame = box.text_frame
    frame.word_wrap = True
    p = frame.paragraphs[0]
    run = p.add_run()
    set_run(run, text, 20, color=NAVY, font="Consolas")


def render_table(slide, headers: list[str], rows: list[list[str]]) -> None:
    rows_n = 1 + len(rows)
    cols_n = len(headers)
    table_shape = slide.shapes.add_table(rows_n, cols_n, Inches(0.45), Inches(1.2), Inches(12.4), Inches(0.48 * rows_n))
    table = table_shape.table
    for col, header in enumerate(headers):
        cell = table.cell(0, col)
        cell.text = ""
        p = cell.text_frame.paragraphs[0]
        run = p.add_run()
        set_run(run, header, 14, bold=True, color=WHITE)
        _fill(cell, NAVY)
    for r, row in enumerate(rows, start=1):
        for c, value in enumerate(row):
            cell = table.cell(r, c)
            cell.text = ""
            p = cell.text_frame.paragraphs[0]
            run = p.add_run()
            set_run(run, value, 13, color=TEXT)
            if r % 2 == 0:
                _fill(cell, RGBColor(0xF7, 0xFA, 0xFC))


def _fill(cell, color: RGBColor) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    solid = tc_pr.makeelement(qn("a:solidFill"), {})
    srgb = solid.makeelement(qn("a:srgbClr"), {"val": str(color)})
    solid.append(srgb)
    tc_pr.append(solid)


